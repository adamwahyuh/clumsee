export type Key = keyof typeof en

let lang: Lang = 'id'

/** Main calls this on startup and when settings change; each renderer when it gets the settings. */
export function setLang(l: Lang): void {
  lang = l
  if (typeof document !== 'undefined') document.documentElement.lang = l
}

/** Translates a key, filling {0}, {1}… with args. */
export const t = (key: Key, ...args: (string | number)[]): string =>
  (lang === 'en' ? en[key] : key).replace(/\{(\d)\}/g, (_, i) => String(args[Number(i)]))

export const isKey = (s: string): s is Key => s in en
